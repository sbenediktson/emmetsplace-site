const { test } = require('node:test');
const assert = require('node:assert');
const { esc, SITE_URL } = require('../site/html');
const { renderEpisodePage, renderMusicianPage, renderWriterPage, episodeUrl, musicianUrl } = require('../site/pages');

const ep = (o = {}) => ({
  id: 'abc123', title: "Live From Emmet's Place Vol. 134 - Kurt Elling", number: 134, guests: 'Kurt Elling',
  streamDate: '2025-03-03T20:00:00Z', year: 2025, duration: 5400, location: 'Harlem, New York',
  artists: [{ name: 'Kurt Elling', instrument: 'vocals' }, { name: 'Joe Farnsworth', instrument: 'drums' }],
  songs: [{ title: 'Nature Boy', start: 125 }], description: '', restreams: [{ id: 'rs1', title: 'Re-Stream Vol. 134' }], ...o,
});
const ctx = {
  slugs: { abc123: 'vol-134-kurt-elling', n1: 'vol-135' },
  musicianSlugs: { 'Kurt Elling': 'kurt-elling', 'Joe Farnsworth': 'joe-farnsworth' },
};
const desc = (html) => html.match(/<meta name="description" content="([^"]*)"/)[1];

test('esc escapes the five characters', () => {
  assert.strictEqual(esc(`&<>"'`), '&amp;&lt;&gt;&quot;&#39;');
});

test('url helpers', () => {
  assert.strictEqual(episodeUrl('x'), '/episodes/x/');
  assert.strictEqual(musicianUrl('y'), '/musicians/y/');
  assert.strictEqual(SITE_URL, 'https://emmetsplace.com');
});

test('episode page has head metadata, embed, links and setlist', () => {
  const html = renderEpisodePage(ep(), { ...ctx, next: ep({ id: 'n1', number: 135, guests: 'Ann' }) });
  assert.match(html, /^<!DOCTYPE html>\n<!-- generated by build-site\.js -->/);
  assert.ok(html.includes('<title>Kurt Elling - Live From Emmet&#39;s Place Vol. 134 (2025)</title>'));
  assert.ok(html.includes('<link rel="canonical" href="https://emmetsplace.com/episodes/vol-134-kurt-elling/">'));
  assert.ok(html.includes('property="og:url" content="https://emmetsplace.com/episodes/vol-134-kurt-elling/"'));
  assert.ok(html.includes('youtube.com/embed/abc123'));
  assert.ok(html.includes('href="https://www.youtube.com/watch?v=abc123"'));
  assert.ok(html.includes('https://www.youtube.com/watch?v=abc123&amp;t=125'));
  assert.ok(html.includes('Harlem, New York'));
  assert.ok(html.includes('March 3, 2025'));
  assert.ok(html.includes('href="/musicians/kurt-elling/"'));
  assert.ok(html.includes('href="https://www.youtube.com/watch?v=rs1"'));
  assert.ok(html.includes('href="/episodes/vol-135/"'));
  assert.ok(html.includes('href="/page.css"'));
  assert.ok(!html.includes('writers/'));
  assert.ok(desc(html).length <= 160);
});

test('bare episode has no Lineup/Setlist and no undefined', () => {
  const html = renderEpisodePage(ep({ artists: [], songs: [], streamDate: null, year: null, location: null, restreams: [] }), ctx);
  assert.ok(!html.includes('Lineup'));
  assert.ok(!html.includes('Setlist'));
  assert.ok(!html.includes('undefined'));
  assert.ok(!html.includes('null'));
  assert.ok(desc(html).length > 20);
});

test('hostile title is escaped everywhere', () => {
  const bad = '<script>&"';
  const html = renderEpisodePage(ep({ number: null, guests: null, title: bad, artists: [{ name: bad, instrument: bad }], songs: [{ title: bad, start: 1 }], restreams: [{ id: 'x', title: bad }], location: bad }), ctx);
  assert.ok(!html.includes('<script>'));
  assert.ok(html.includes('&lt;script&gt;&amp;&quot;'));
});

test('long descriptions are trimmed to 160', () => {
  const artists = Array.from({ length: 30 }, (_, i) => ({ name: `Musician Number${i}`, instrument: 'x' }));
  assert.ok(desc(renderEpisodePage(ep({ artists }), ctx)).length <= 160);
});

test('musician page lists each appearance once', () => {
  const e = ep();
  const html = renderMusicianPage({ name: 'Joe Farnsworth', instruments: ['drums'], appearances: [e] }, ctx);
  assert.ok(html.includes('<link rel="canonical" href="https://emmetsplace.com/musicians/joe-farnsworth/">'));
  assert.ok(html.includes('drums'));
  assert.strictEqual(html.split('href="/episodes/vol-134-kurt-elling/"').length - 1, 1);
  assert.ok(desc(html).length <= 160);
  assert.ok(!html.includes('writers/'));
});

test('writer page is noindex and lists episodes', () => {
  const html = renderWriterPage({ slug: 'sam', name: 'Sam', bio: 'Hi <b>', episodeIds: ['abc123'] }, [ep(), ep({ id: 'zzz' })], ctx);
  assert.ok(html.includes('<meta name="robots" content="noindex,nofollow">'));
  assert.ok(html.includes('Hi &lt;b&gt;'));
  assert.ok(html.includes('href="/episodes/vol-134-kurt-elling/"'));
  assert.ok(!html.includes('zzz'));
});
